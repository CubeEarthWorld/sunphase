#[test]
fn range_mode_and_week_start() {
    let p = Parser::default();
    let mut o = opts();
    o.range = true;

    // Range lengths in parse() and parse_ranges().
    let next_week_expanded = p.parse("الأسبوع القادم", &o).unwrap();
    assert_eq!(next_week_expanded.len(), 7);
    assert_eq!(
        next_week_expanded[0].date.to_string(),
        "2025-02-09 00:00:00"
    );
    assert_eq!(
        next_week_expanded[6].date.to_string(),
        "2025-02-15 00:00:00"
    );
    assert_eq!(
        p.parse_ranges("الأسبوع القادم", &o).unwrap()[0].range_days,
        Some(7)
    );

    let next_month_expanded = p.parse("الشهر القادم", &o).unwrap();
    assert_eq!(next_month_expanded.len(), 31);
    assert_eq!(
        next_month_expanded[0].date.to_string(),
        "2025-03-01 00:00:00"
    );
    assert_eq!(
        next_month_expanded[30].date.to_string(),
        "2025-03-31 00:00:00"
    );
    assert_eq!(
        p.parse_ranges("الشهر القادم", &o).unwrap()[0].range_days,
        Some(31)
    );

    assert_eq!(p.parse("هذا الشهر", &o).unwrap().len(), 28);
    assert_eq!(
        p.parse_ranges("هذا الشهر", &o).unwrap()[0].range_days,
        Some(28)
    );

    let within_3 = p.parse("خلال 3 أيام", &o).unwrap();
    assert_eq!(within_3.len(), 4);
    assert_eq!(within_3[0].date.to_string(), "2025-02-08 00:00:00");
    assert_eq!(within_3[3].date.to_string(), "2025-02-11 00:00:00");
    assert_eq!(
        p.parse_ranges("خلال 3 أيام", &o).unwrap()[0].range_days,
        Some(4)
    );
    assert_eq!(p.parse("خلال يومين", &o).unwrap().len(), 3);
    assert_eq!(
        p.parse_ranges("خلال يومين", &o).unwrap()[0].range_days,
        Some(3)
    );
    assert_eq!(p.parse("خلال أسبوع", &o).unwrap().len(), 8);
    assert_eq!(
        p.parse_ranges("خلال أسبوع", &o).unwrap()[0].range_days,
        Some(8)
    );
    assert_eq!(p.parse("خلال أسبوعين", &o).unwrap().len(), 15);

    // Multi-match document order (sorted by m.start).
    let text = "الاجتماع غداً الساعة 10 صباحاً والمؤتمر في 20 مارس";
    let mut multi = p.parse(text, &o).unwrap();
    multi.sort_by_key(|m| m.start);
    assert_eq!(multi.len(), 2);
    assert_eq!(&text[multi[0].start..multi[0].end], "غداً الساعة 10 صباحاً");
    assert_eq!(multi[0].date.to_string(), "2025-02-09 10:00:00");
    assert_eq!(&text[multi[1].start..multi[1].end], "20 مارس");
    assert_eq!(multi[1].date.to_string(), "2025-03-20 00:00:00");

    // week_start = 1 (Monday) vs 7 (Sunday) on Saturday 2025-02-08.
    o.range = false;
    for (ws, this_w, next_w, last_w) in [
        (
            7,
            "2025-02-02 00:00:00",
            "2025-02-09 00:00:00",
            "2025-01-26 00:00:00",
        ),
        (
            1,
            "2025-02-03 00:00:00",
            "2025-02-10 00:00:00",
            "2025-01-27 00:00:00",
        ),
    ] {
        o.week_start = ws;
        assert_exact_with("هذا الأسبوع", this_w, &o);
        assert_exact_with("الأسبوع القادم", next_w, &o);
        assert_exact_with("الأسبوع الماضي", last_w, &o);
    }

    // week_start = 1 vs 7 on Wednesday 2025-02-12.
    o.reference = "2025-02-12T11:05:00".parse().unwrap();
    for (ws, sun_expected) in [(1, "2025-02-09 00:00:00"), (7, "2025-02-02 00:00:00")] {
        o.week_start = ws;
        assert_exact_with("الأسبوع الماضي الاثنين", "2025-02-03 00:00:00", &o);
        assert_exact_with("الأسبوع الماضي الأحد", sun_expected, &o);
    }
}

#[test]
fn negative_and_boundary_cases() {
    // Attached letters, non-date function words, Hijri markers, and unit guards rejected.
    for text in [
        "اليومي",
        "أمسية",
        "أمسك",
        "أحدهم",
        "الأحداث",
        "لا أحد هنا",
        "كتابين اثنين",
        "اثنينية",
        "غدار",
        "شهرياً",
        "سنوي",
        "السبتي",
        "15 مارسx",
        "15 مارسأ",
        "الساعة 3مx",
        "١٥مارسأ",
        "عام 1446 هـ",
        "15/03/1446 هـ",
        "15/03/2025هـ",
    ] {
        assert_empty(text);
    }

    // MONTH_DAY_GUARD1 prevents treating percentages or durations after a month as a day of month.
    for text in ["مارس 15%", "مارس 15 دقيقة"] {
        assert_date(text, "2025-03-01 00:00:00");
    }

    // Invalid dates, times, weekday mismatches, missing 5th occurrence, bare meridiem, overflow.
    for text in [
        "30 فبراير 2025",
        "29 فبراير 2025",
        "31 أبريل 2025",
        "31 نيسان 2025",
        "32 مارس 2025",
        "0 مارس 2025",
        "32/03/2025",
        "00/03/2025",
        "32-03-2025",
        "00-03-2025",
        "30/02/2025",
        "31/04/2025",
        "25:00",
        "12:60",
        "الساعة 25",
        "الساعة 14:75",
        "٢٥:٠٠",
        "٣٠ فبراير ٢٠٢٥",
        "الاثنين 11 فبراير 2025",
        "الاثنين الخامس من فبراير",
        "صباحاً",
        "مساءً",
        "ليلاً",
        "ظهراً",
        "بعد 999999999999999999999 يوماً",
    ] {
        assert_empty(text);
    }

    // Spoken minute modifier guard prevents absorbing a day number before a month name.
    assert_date("3 و 15 مارس", "2025-03-15 00:00:00");

    // RangeTooLarge on oversized within-days range.
    let p = Parser::default();
    let mut o = opts();
    o.range = true;
    assert_eq!(p.parse("خلال 999999 يوماً", &o), Err(Error::RangeTooLarge));

    // Non-date words must not be swallowed by glue.
    for (text, expected_count, forbidden_a, forbidden_b) in [
        ("غداً اجتماع مهم الساعة 3 مساءً", 2, "اجتماع", "مهم"),
        ("اليوم تقرير عاجل غداً", 2, "تقرير", "عاجل"),
    ] {
        let mut res = p.parse(text, &o).unwrap();
        res.sort_by_key(|m| m.start);
        assert_eq!(res.len(), expected_count, "for `{text}`");
        assert!(res.iter().all(|m| {
            let span = &text[m.start..m.end];
            !span.contains(forbidden_a) && !span.contains(forbidden_b)
        }));
    }
}
