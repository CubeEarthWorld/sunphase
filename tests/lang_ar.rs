use sunphase::{Error, NaiveDate, NaiveDateTime, Options, Parser};

fn ref_dt() -> NaiveDateTime {
    NaiveDate::from_ymd_opt(2025, 2, 8)
        .unwrap()
        .and_hms_opt(11, 5, 0)
        .unwrap()
}

fn opts() -> Options<'static> {
    let mut o = Options::new(ref_dt());
    o.languages = &["ar"];
    o
}

fn assert_exact_with(input: &str, expected: &str, o: &Options<'_>) {
    let p = Parser::default();
    let results = p.parse(input, o).unwrap();
    assert_eq!(
        results.len(),
        1,
        "expected 1 match for `{input}`, got {results:?}"
    );
    let m = &results[0];
    assert!(
        input.is_char_boundary(m.start) && input.is_char_boundary(m.end),
        "non-char-boundary span for `{input}`: {}..{}",
        m.start,
        m.end
    );
    assert_eq!(
        &input[m.start..m.end],
        input,
        "expected full span for `{input}`, got `{}`",
        &input[m.start..m.end]
    );
    assert_eq!(m.date.to_string(), expected, "for `{input}`");
}

fn assert_exact(input: &str, expected: &str) {
    assert_exact_with(input, expected, &opts());
}

fn assert_date(input: &str, expected: &str) {
    let p = Parser::default();
    let results = p.parse(input, &opts()).unwrap();
    assert_eq!(
        results.len(),
        1,
        "expected 1 match for `{input}`, got {results:?}"
    );
    let m = &results[0];
    assert!(
        input.is_char_boundary(m.start) && input.is_char_boundary(m.end),
        "non-char-boundary span for `{input}`"
    );
    assert_eq!(m.date.to_string(), expected, "for `{input}`");
}

fn assert_empty(input: &str) {
    let p = Parser::default();
    let results = p.parse(input, &opts()).unwrap();
    assert!(
        results.is_empty(),
        "expected no match for `{input}`, got {results:?}"
    );
}

