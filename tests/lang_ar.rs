#[test]
fn arabic_indic_digits_and_utf8_spans() {
    for (text, expected) in [
        ("١٥ مارس ٢٠٢٥", "2025-03-15 00:00:00"),
        ("١٠ أبريل ٢٠٢٦", "2026-04-10 00:00:00"),
        ("١٥/٠٣/٢٠٢٥", "2025-03-15 00:00:00"),
        ("٠٥/٠٣/٢٠٢٥", "2025-03-05 00:00:00"),
        ("١٥\u{060D}٠٣\u{060D}٢٠٢٥", "2025-03-15 00:00:00"),
        ("٠٥/٠١", "2026-01-05 00:00:00"),
        ("١٤:٣٠", "2025-02-08 14:30:00"),
        ("الساعة ٨:٤٥ صباحاً", "2025-02-09 08:45:00"),
        ("الساعة ٩ ونصف مساءً", "2025-02-08 21:30:00"),
        ("بعد ٧ أيام", "2025-02-15 00:00:00"),
        ("منذ ٦ أشهر", "2024-08-01 00:00:00"),
        ("خلال ٣ أيام", "2025-02-08 00:00:00"),
    ] {
        assert_exact(text, expected);
    }

    let p = Parser::default();
    let mut o = opts();
    o.range = true;

    let input = "😀 غداً الساعة ١٠:٣٠ صباحاً و الشهر القادم";
    let mut results = p.parse(input, &o).unwrap();
    results.sort_by_key(|m| m.start);
    assert!(
        results
            .iter()
            .any(|r| &input[r.start..r.end] == "غداً الساعة ١٠:٣٠ صباحاً"
                && r.date.to_string() == "2025-02-09 10:30:00")
    );
    assert!(
        results
            .iter()
            .any(|r| &input[r.start..r.end] == "الشهر القادم"
                && r.date.to_string() == "2025-03-01 00:00:00")
    );

    // Earlier normalized Arabic-Indic digits must not shift later UTF-8 spans.
    let input = "٩😀 بعد ٣ أيام؛ 😀 بعد ١٢ يوماً؛ انتهى";
    let mut matches = p.parse(input, &o).unwrap();
    matches.sort_by_key(|m| m.start);
    let spans: Vec<_> = matches
        .iter()
        .map(|r| {
            assert!(input.is_char_boundary(r.start) && input.is_char_boundary(r.end));
            &input[r.start..r.end]
        })
        .collect();
    assert_eq!(spans, ["بعد ٣ أيام", "بعد ١٢ يوماً"]);
    assert_eq!(matches[0].date.to_string(), "2025-02-11 00:00:00");
    assert_eq!(matches[1].date.to_string(), "2025-02-20 00:00:00");
}

