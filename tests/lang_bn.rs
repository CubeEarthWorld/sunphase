#[test]
fn native_digits_and_exact_utf8_spans() {
    let p = Parser::default();
    let mut o = options();
    o.range = true;

    let input = "😀 আগামীকাল ১০টা ৩০ মিনিটে এবং আগামী মাস";
    let results = p.parse(input, &o).unwrap();
    assert!(results.iter().any(|r| {
        input.is_char_boundary(r.start)
            && input.is_char_boundary(r.end)
            && &input[r.start..r.end] == "আগামীকাল ১০টা ৩০ মিনিটে"
            && r.date.to_string() == "2025-02-09 10:30:00"
    }));
    assert!(results.iter().any(|r| {
        input.is_char_boundary(r.start)
            && input.is_char_boundary(r.end)
            && &input[r.start..r.end] == "আগামী মাস"
    }));

    // Earlier normalized Bengali digits must not shift later UTF-8 offsets.
    let input = "৯😀 ৩ দিন পর; 😀 ১২ দিন পর; শেষ";
    let mut matches = p.parse(input, &o).unwrap();
    matches.sort_by_key(|m| m.start);
    let spans: Vec<_> = matches
        .iter()
        .map(|r| {
            assert!(input.is_char_boundary(r.start) && input.is_char_boundary(r.end));
            &input[r.start..r.end]
        })
        .collect();
    assert_eq!(spans, ["৩ দিন পর", "১২ দিন পর"]);
    assert_eq!(matches[0].date.to_string(), "2025-02-11 00:00:00");
    assert_eq!(matches[1].date.to_string(), "2025-02-20 00:00:00");

    let expected = p.parse(input, &o).unwrap();
    o.languages = &["bn", "bn", "universal", "universal"];
    assert_eq!(p.parse(input, &o).unwrap(), expected);
}

