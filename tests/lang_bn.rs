#[test]
fn range_mode_multi_match_and_bounds() {
    let p = Parser::default();
    let mut o = options();
    o.range = true;

    assert_eq!(p.parse("আগামী সপ্তাহ", &o).unwrap().len(), 7);
    assert_eq!(p.parse("এই মাস", &o).unwrap().len(), 28);
    assert_eq!(p.parse("আগামী মাস", &o).unwrap().len(), 31);

    let week_range = p.parse_ranges("আগামী সপ্তাহ", &o).unwrap();
    assert_eq!(week_range.len(), 1);
    assert_eq!(week_range[0].range_type, Some("week"));
    assert_eq!(week_range[0].range_days, Some(7));

    let month_range = p.parse_ranges("আগামী মাস", &o).unwrap();
    assert_eq!(month_range.len(), 1);
    assert_eq!(month_range[0].range_type, Some("month"));
    assert_eq!(month_range[0].range_days, Some(31));

    // Range mode sorts by length/score; sort by m.start to verify document order.
    let doc = "মিটিং আগামীকাল সকাল ১০টায়, এবং রিপোর্ট ১৫ মার্চ বিকাল ৪টায় জমা দিতে হবে।";
    let mut matches = p.parse(doc, &o).unwrap();
    matches.sort_by_key(|m| m.start);
    assert_eq!(matches.len(), 2);
    assert_eq!(&doc[matches[0].start..matches[0].end], "আগামীকাল সকাল ১০টায়");
    assert_eq!(matches[0].date.to_string(), "2025-02-09 10:00:00");
    assert_eq!(&doc[matches[1].start..matches[1].end], "১৫ মার্চ বিকাল ৪টায়");
    assert_eq!(matches[1].date.to_string(), "2025-03-15 16:00:00");

    assert_eq!(p.parse("৯৯৯৯৯৯ দিনের মধ্যে", &o), Err(Error::RangeTooLarge));
    assert!(
        p.parse("৯৯৯৯৯৯৯৯৯৯৯৯৯৯৯৯৯৯৯৯৯ দিন পর", &o)
            .unwrap()
            .is_empty()
    );
}

