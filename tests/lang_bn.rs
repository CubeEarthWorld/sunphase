use sunphase::{Error, NaiveDate, NaiveDateTime, Options, Parser};

fn ref_dt(y: i32, m: u32, d: u32, h: u32, min: u32, s: u32) -> NaiveDateTime {
    NaiveDate::from_ymd_opt(y, m, d)
        .unwrap()
        .and_hms_opt(h, min, s)
        .unwrap()
}

fn options() -> Options<'static> {
    let mut o = Options::new(ref_dt(2025, 2, 8, 11, 5, 0));
    o.languages = &["bn"];
    o
}

fn assert_parses(p: &Parser, o: &Options<'_>, cases: &[(&str, &str)]) {
    for &(input, expected) in cases {
        let res = p.parse(input, o).unwrap();
        assert!(!res.is_empty(), "expected match for `{input}`");
        assert_eq!(res[0].date.to_string(), expected, "input: `{input}`");
    }
}

