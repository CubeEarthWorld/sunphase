use sunphase::{NaiveDate, NaiveDateTime, Options, Parser, parse_with};

fn dt(y: i32, m: u32, d: u32, h: u32, min: u32) -> NaiveDateTime {
    NaiveDate::from_ymd_opt(y, m, d)
        .unwrap()
        .and_hms_opt(h, min, 0)
        .unwrap()
}

fn ref_dt() -> NaiveDateTime {
    dt(2025, 2, 8, 11, 5)
}

fn ru_opts(range: bool, week_start: u8) -> Options<'static> {
    let mut o = Options::new(ref_dt());
    o.languages = &["ru"];
    o.range = range;
    o.week_start = week_start;
    o
}

fn assert_ru(input: &str, expected_slice: &str, expected_date: NaiveDateTime) {
    let matches = parse_with(input, &ru_opts(false, 7)).unwrap();
    assert_eq!(
        matches.len(),
        1,
        "expected 1 match for {input:?}, got {matches:?}"
    );
    let m = &matches[0];
    assert_eq!(
        &input[m.start..m.end],
        expected_slice,
        "unexpected UTF-8 span for {input:?}"
    );
    assert_eq!(m.date, expected_date, "unexpected date for {input:?}");
}

fn assert_ru_none(input: &str) {
    let matches = parse_with(input, &ru_opts(false, 7)).unwrap();
    assert!(
        matches.is_empty(),
        "expected no match for {input:?}, got {matches:?}"
    );
}

