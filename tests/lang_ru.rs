#[test]
fn utf8_spans_composition_and_ranges() {
    let text = "Встреча перенесена на пятницу, 14 февраля 2025 года в 15:30 в офисе";
    assert_ru(
        text,
        "пятницу, 14 февраля 2025 года в 15:30",
        dt(2025, 2, 14, 15, 30),
    );

    let week_sun = parse_with("на следующей неделе", &ru_opts(true, 7)).unwrap();
    assert_eq!(week_sun.len(), 7);
    assert_eq!(week_sun[0].date, dt(2025, 2, 9, 0, 0));
    assert_eq!(week_sun[6].date, dt(2025, 2, 15, 0, 0));

    let week_mon = parse_with("на следующей неделе", &ru_opts(true, 1)).unwrap();
    assert_eq!(week_mon.len(), 7);
    assert_eq!(week_mon[0].date, dt(2025, 2, 10, 0, 0));
    assert_eq!(week_mon[6].date, dt(2025, 2, 16, 0, 0));

    let next_month = parse_with("в следующем месяце", &ru_opts(true, 1)).unwrap();
    assert_eq!(next_month.len(), 31);
    assert_eq!(next_month[0].date, dt(2025, 3, 1, 0, 0));
    assert_eq!(next_month[30].date, dt(2025, 3, 31, 0, 0));

    let mut multi = parse_with(
        "Встреча завтра в 10:00, а дедлайн в пятницу в 18:00",
        &ru_opts(true, 1),
    )
    .unwrap();
    multi.sort_by_key(|m| m.start);
    assert_eq!(multi.len(), 2);
    assert_eq!(multi[0].date, dt(2025, 2, 9, 10, 0));
    assert_eq!(multi[1].date, dt(2025, 2, 14, 18, 0));
}

